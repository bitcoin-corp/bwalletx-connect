#!/usr/bin/env node
/**
 * The licence payload for what the one-script-tag build (dist/bwalletx-connect.global.js) bundles: @bsv/sdk and
 * qrcode-generator. Copies @bsv/sdk's own LICENSE, NOTICE, PATENTS, THIRD_PARTY_NOTICES.md and LICENSES/ verbatim into
 * third-party/bsv-sdk/ (its notices say to keep all of them with browser bundles), and writes THIRD_PARTY_LICENSES.md.
 *
 *   node scripts/third-party-licenses.mjs           write
 *   node scripts/third-party-licenses.mjs --check   exit 1 if the committed copy differs from the installed packages
 *
 * Run it after the lockfile moves @bsv/sdk or qrcode-generator; test/third-party-licenses.test.ts fails until you do.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SDK = join(root, 'node_modules', '@bsv', 'sdk');
const QR = join(root, 'node_modules', 'qrcode-generator');
const OUT = join(root, 'third-party', 'bsv-sdk');
const INDEX = join(root, 'THIRD_PARTY_LICENSES.md');
const SDK_PAYLOAD = ['LICENSE', 'NOTICE', 'PATENTS', 'THIRD_PARTY_NOTICES.md', 'LICENSES'];

const pkg = (dir) => JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));

