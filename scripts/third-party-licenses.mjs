function listFiles(dir, base = dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? listFiles(join(dir, e.name), base) : [relative(base, join(dir, e.name))],
  );
}

/** Differences between the committed copy and the installed packages; empty when they match. */
export function differences() {
  const out = [];
  if (!existsSync(INDEX) || readFileSync(INDEX, 'utf8') !== indexText()) out.push('THIRD_PARTY_LICENSES.md');
  const want = SDK_PAYLOAD.filter((p) => existsSync(join(SDK, p))).flatMap((p) => (p === 'LICENSES' ? listFiles(join(SDK, p)).map((f) => join(p, f)) : [p]));
  const have = existsSync(OUT) ? listFiles(OUT) : [];
  for (const f of want) {
    if (!have.includes(f) || !readFileSync(join(SDK, f)).equals(readFileSync(join(OUT, f)))) out.push(`third-party/bsv-sdk/${f}`);
  }
  for (const f of have) if (!want.includes(f)) out.push(`third-party/bsv-sdk/${f} (not in @bsv/sdk)`);
  return out;
}

function write() {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  for (const p of SDK_PAYLOAD) if (existsSync(join(SDK, p))) cpSync(join(SDK, p), join(OUT, p), { recursive: true });
  writeFileSync(INDEX, indexText());
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const d = differences();
    if (d.length) {
      console.error(`Third-party licences are stale; run node scripts/third-party-licenses.mjs:\n  ${d.join('\n  ')}`);
      process.exit(1);
    }
  } else {
    write();
  }
}
